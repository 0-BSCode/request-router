import { existsSync, readFileSync, realpathSync } from "node:fs";
import { resolve } from "node:path";
import { parse } from "dotenv";

const input = process.env.INPUT_ENV_FILE ?? ".env.deploy";
const generated = ["DATABASE_URL", "BETTER_AUTH_URL", "BETTER_AUTH_SECRET"];
let values = {};
try {
  if (
    resolve(input) === resolve(".env.production") ||
    (existsSync(input) &&
      existsSync(".env.production") &&
      realpathSync(input) === realpathSync(".env.production"))
  ) {
    throw new Error(
      "Use .env.deploy or another private input file; .env.production is generated output.",
    );
  }
  if (existsSync(input)) {
    values = parse(readFileSync(input));
    for (const [key, value] of Object.entries(values)) {
      if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(key) || /[\r\n\0]/.test(value)) {
        throw new Error("Input must contain valid environment names and single-line values.");
      }
      if (generated.includes(key)) {
        throw new Error(
          `${key} is generated by setup. Remove it from the input file or configure Coolify manually.`,
        );
      }
    }
  } else if (process.env.INPUT_ENV_FILE !== undefined) {
    throw new Error("INPUT_ENV_FILE does not exist.");
  }
} catch (error) {
  console.error(error.code ? "Unable to read the deployment input file." : error.message);
  process.exit(1);
}

const [mode, ...keys] = process.argv.slice(2);
if (mode === "get") {
  const value = process.env[keys[0]] ?? values[keys[0]] ?? "";
  if (/[\r\n\0]/.test(value)) {
    console.error("Runtime values must be single-line.");
    process.exit(1);
  }
  process.stdout.write(value);
} else if (mode === "append") {
  for (const [key, value] of Object.entries(values)) {
    // Coolify strips the outer quotes and preserves everything inside literally.
    if (!keys.includes(key)) process.stdout.write(`${key}='${value}'\n`);
  }
} else if (mode !== "validate") {
  throw new Error("Expected validate, get KEY, or append [EXCLUDED_KEYS].");
}
